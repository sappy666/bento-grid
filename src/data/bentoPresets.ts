// Procedural generator for arbitrary counts or fallback
export function generateProceduralLayout(count: number): BentoLayoutPreset {
  const cards: BentoCard[] = [];
  const types: CardType[] = ['featured', 'metric', 'image', 'list', 'action', 'media', 'quote'];
  
  for (let i = 0; i < count; i++) {
    const cardType = types[i % types.length];
    const isHero = i === 0;
    const isWide = i === 1 || (i % 4 === 0 && i !== 0);

    let colSpanDesktop = 1;
    let rowSpanDesktop = 1;

    if (isHero && count >= 3) {
      colSpanDesktop = 2;
      rowSpanDesktop = count >= 4 ? 2 : 1;
    } else if (isWide) {
      colSpanDesktop = 2;
      rowSpanDesktop = 1;
    }

    cards.push({
      id: `gen-card-${i + 1}`,
      type: cardType,
      title: `Elemento Bento #${i + 1}`,
      colSpanDesktop,
      rowSpanDesktop,
      colSpanTablet: colSpanDesktop > 1 ? 2 : 1,
      rowSpanTablet: 1,
      content: {
        title: cardType === 'featured' ? 'Funcionalidad Destacada' : `Módulo Bento ${i + 1}`,
        subtitle: 'Diseñado con proporciones áureas para CSS Grid.',
        badge: `Bento #${i + 1}`,
        badgeColor: (['blue', 'purple', 'green', 'amber', 'rose'][i % 5]) as any,
        metricValue: cardType === 'metric' ? `${(i + 1) * 24.5}k` : undefined,
        metricLabel: cardType === 'metric' ? 'Métrica de Rendimiento' : undefined,
        metricChange: cardType === 'metric' ? `+${(i + 1) * 7}%` : undefined,
        metricIsPositive: true,
        imageUrl: (cardType === 'image' || cardType === 'featured') ? SAMPLE_IMAGES[i % SAMPLE_IMAGES.length] : undefined,
        listItems: cardType === 'list' ? [
          { text: 'Composición Bento adaptable', done: true },
          { text: 'Soporte para Dark y Light Mode', done: true },
        ] : undefined,
        actionText: cardType === 'action' ? 'Activo' : undefined,
        actionActive: true,
      },
    });
  }

  return {
    id: `procedural-${count}`,
    name: `Diseño Dinámico (${count} Cards)`,
    description: `Generación algorítmica balanceada para rejilla de ${count} elementos.`,
    tag: 'Dinámico',
    cards,
  };
}
